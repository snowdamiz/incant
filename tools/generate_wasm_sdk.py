#!/usr/bin/env python3
"""Generate the native Wasm ABI contracts; JSON is a build-time source only."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import shutil
import re

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT/'sdk/abi/native-v1.json'
SIZES = {'u8': 1, 'u32': 4, 'u64': 8, 'i64': 8, 'u128': 16, 'f64': 8}


def validate(data):
    required = {'registry_version','abi_version','endianness','id_endianness','functions','constants','magic','enums','input_sections','records','optional_none','namespaces'}
    if set(data) != required: raise ValueError('unknown/missing registry fields')
    if data['id_endianness'] != 'big' or data['optional_none'] != -1: raise ValueError('unsupported identity/optional representation')
    if not data['namespaces'] or data['namespaces'].get('incant_v1') != 'imports': raise ValueError('missing base namespace')
    for namespace, field in data['namespaces'].items():
        if not re.fullmatch(r'incant(?:_[a-z]+)*_v[1-9][0-9]*',namespace) or not re.fullmatch(r'[a-z][a-z0-9]*',field): raise ValueError('invalid namespace')
    for f in data['functions']:
        if set(f) != {'namespace','name','opcode','params','result','call'} or f['namespace'] not in data['namespaces']: raise ValueError('unknown import definition')
        if f['params'][0] != ['epoch','i64'] or len(f['params']) > 5 or any(t != 'i32' for _,t in f['params'][1:]) or f['result'] not in (None,'i32'): raise ValueError('unsupported import signature')
        if len({n for n,_ in f['params']}) != len(f['params']): raise ValueError('duplicate parameter')
    for name, fields in data['records'].items():
        if not fields or len({f[0] for f in fields}) != len(fields): raise ValueError('duplicate/empty record')
        for f in fields:
            if len(f) not in (2,3) or f[1] not in SIZES or (len(f)==3 and (type(f[2]) is not int or not 1 <= f[2] <= 128)): raise ValueError('invalid field layout')
    for value in data['constants'].values():
        if type(value) is not int or not 0 < value <= 2**31-1: raise ValueError('invalid bound')
    if any(len(v.encode('ascii')) != 8 for v in data['magic'].values()): raise ValueError('invalid wire magic')
    if len(set(data['input_sections'])) != len(data['input_sections']): raise ValueError('duplicate section')


def generate(data, digest):
    validate(data)
    if data['registry_version'] != 1 or data['abi_version'] != 1 or data['endianness'] != 'little':
        raise ValueError('unsupported registry version/endianness')
    funcs=data['functions']
    if [f['opcode'] for f in funcs] != list(range(len(funcs))) or len({(f['namespace'],f['name']) for f in funcs}) != len(funcs):
        raise ValueError('duplicate or noncontiguous imports')
    banner=f'// Generated by tools/generate_wasm_sdk.py; registry SHA256 {digest}.\n'
    shared=[banner,'#![no_std]\n#![forbid(unsafe_code)]\n',f'pub const ABI_VERSION: i32 = {data["abi_version"]};\n']
    if 'incant_localization_v1' in data['namespaces']:
        shared.append('pub mod localization;\n')
    if 'incant_navigation_v1' in data['namespaces']:
        shared.append('pub mod steering;\npub mod navigation_paths;\n')
    if 'incant_physics_v1' in data['namespaces']:
        shared.append('pub mod physics;\n')
    shared.append('pub mod hud;\npub mod persistent;\n')
    if 'incant_audio_v1' in data['namespaces']:
        shared.append('pub mod audio;\n')
        shared += ['pub const AUDIO_MAX_BYTES: usize = AudioHeader::SIZE + AUDIO_MAX_NODES * AudioRow::SIZE;\n', 'pub const AUDIO_MAX_COMMAND_BYTES: usize = AudioCommandHeader::SIZE + AUDIO_MAX_COMMANDS * AudioCommand::SIZE;\n']
    if 'incant_haptics_v1' in data['namespaces']:
        shared += ['pub mod haptics;\n', 'pub const HAPTIC_MAX_BYTES: usize = HapticHeader::SIZE + HAPTIC_MAX_TARGETS * HapticTarget::SIZE;\n', 'pub const HAPTIC_MAX_COMMAND_BYTES: usize = HapticCommandHeader::SIZE + HAPTIC_MAX_REQUESTS * HapticCommand::SIZE;\n']
    if 'incant_light_v1' in data['namespaces']:
        shared += ['pub mod light;\n', 'pub const LIGHT_MAX_COMMAND_BYTES: usize = LightCommandHeader::SIZE + LIGHT_MAX_COMMANDS * LightCommand::SIZE;\n']
    shared += [f'pub const {name}: usize = {value};\n' for name,value in data['constants'].items()]
    shared += [f'pub const {name}: &[u8; 8] = b"{value}";\n' for name,value in data['magic'].items()]
    shared += ['pub const HUD_MAX_BYTES: usize = HudHeader::SIZE + HUD_MAX_WIDGETS * HudWidget::SIZE + HUD_MAX_TEXTS * HudText::SIZE + HUD_MAX_EVENTS * HudEvent::SIZE + HUD_MAX_DECLARATION_BYTES + HUD_MAX_EVENT_BYTES;\n']
    shared += ['pub const ROOT_MOTION_MAX_BYTES: usize = RootMotionHeader::SIZE + ANIMATION_IK_V2_MAX_BYTES + ROOT_MOTION_MAX_ROWS * RootMotionRow::SIZE;\n']
    shared += ['pub const ANIMATION_V5_MAX_BYTES: usize = AnimationHeaderV5::SIZE + ANIMATION_MAX_ROWS * AnimationRowV4::SIZE + ANIMATION_POSE_MAX_SAMPLE_ROWS * AnimationPoseSample::SIZE + ANIMATION_COMPOUND_MAX_ROWS * AnimationPoseGroups::SIZE;\n',
               'pub const ANIMATION_IK_V2_MAX_BYTES: usize = AnimationIkHeader::SIZE + ANIMATION_V5_MAX_BYTES + ANIMATION_IK_MAX_ROWS * AnimationIkRow::SIZE;\n',
               'pub const ANIMATION_GRAPH_V2_MAX_BYTES: usize = AnimationGraphHeaderV2::SIZE + ANIMATION_GRAPH_MAX_BYTES + ANIMATION_GRAPH_MAX_ROWS * AnimationGraphFade::SIZE;\n']
    shared += ['pub const ANIMATION_IK_MAX_BYTES: usize = AnimationIkHeader::SIZE + ANIMATION_V4_MAX_BYTES + ANIMATION_IK_MAX_ROWS * AnimationIkRow::SIZE;\n',
               'pub const ANIMATION_V4_MAX_BYTES: usize = AnimationHeaderV4::SIZE + ANIMATION_MAX_ROWS * AnimationRowV4::SIZE + ANIMATION_POSE_MAX_SAMPLE_ROWS * AnimationPoseSample::SIZE;\n',
               'pub const ANIMATION_V3_MAX_BYTES: usize = AnimationHeader::SIZE + ANIMATION_MAX_ROWS * AnimationRowV3::SIZE;\n',
               'pub const ANIMATION_GRAPH_MAX_BYTES: usize = AnimationGraphHeader::SIZE + ANIMATION_GRAPH_MAX_ROWS * AnimationGraphRow::SIZE + ANIMATION_GRAPH_MAX_PARAMETER_ROWS * AnimationGraphParameter::SIZE;\n',
               'pub const ANIMATION_V2_MAX_BYTES: usize = AnimationHeader::SIZE + ANIMATION_MAX_ROWS * AnimationRowV2::SIZE;\n',
               'pub const ANIMATION_MAX_BYTES: usize = AnimationHeader::SIZE + ANIMATION_MAX_ROWS * AnimationRow::SIZE;\n',
               'pub const FLIPBOOK_MAX_BYTES: usize = FlipbookHeader::SIZE + FLIPBOOK_MAX_ROWS * Flipbook::SIZE;\n',
               '#[derive(Clone,Copy,Debug,PartialEq,Eq)] pub enum ValueType { I32, I64 }\n',
               '#[derive(Debug)] pub struct Import { pub namespace: &\'static str, pub name: &\'static str, pub opcode: u32, pub params: &\'static [ValueType], pub results: &\'static [ValueType] }\n',
               'pub const IMPORTS: &[Import] = &[\n']
    for f in funcs:
        params=', '.join('ValueType::'+t.upper() for _,t in f['params']); result='ValueType::'+f['result'].upper() if f['result'] else ''
        shared.append(f'Import {{ namespace: "{f["namespace"]}", name: "{f["name"]}", opcode: {f["opcode"]}, params: &[{params}], results: &[{result}] }},\n')
    shared += ['];\n','pub fn import(namespace: &str,name: &str)->Option<&\'static Import> { IMPORTS.iter().find(|i|i.namespace==namespace && i.name==name) }\n']
    for name,variants in data['enums'].items():
        if len({v for _,v in variants}) != len(variants): raise ValueError('duplicate tag')
        shared += [f'#[derive(Clone,Copy,Debug,PartialEq,Eq)] #[repr(u8)] pub enum {name} {{'+','.join(f'{n}={v}' for n,v in variants)+'}\n',f'impl {name} {{ pub fn from_tag(tag: u8)->Option<Self> {{ match tag {{'+''.join(f'{v}=>Some(Self::{n}),' for n,v in variants)+'_=>None } } }\n']
    shared += ['#[derive(Clone,Copy,Debug,PartialEq,Eq)] pub enum InputSection {'+','.join(data['input_sections'])+'}\n','pub const INPUT_SECTIONS: &[InputSection] = &['+','.join('InputSection::'+s for s in data['input_sections'])+'];\n']
    for name,fields in data['records'].items():
        size=sum(SIZES[t]*(n[0] if n else 1) for _,t,*n in fields)
        shared += [f'#[derive(Clone,Copy,Debug,PartialEq)] pub struct {name} {{\n']
        for field,ty,*count in fields:shared.append(f'pub {field}: '+(f'[{ty};{count[0]}]' if count else ty)+',\n')
        shared += ['}\n',f'impl {name} {{ pub const SIZE: usize = {size};\n']
        offset=0
        for field,ty,*count in fields:
            shared.append(f'pub const {field.upper()}_OFFSET: usize = {offset};\n');offset+=SIZES[ty]*(count[0] if count else 1)
        checks=[(f'self.{field}.iter().all(|v|v.is_finite())' if count else f'self.{field}.is_finite()') for field,ty,*count in fields if ty=='f64']
        shared += ['pub fn is_finite(&self)->bool {'+(' && '.join(checks) or 'true')+'}\n',f'pub fn decode(bytes: &[u8])->Option<Self> {{ let bytes=bytes.get(..Self::SIZE)?; Some(Self {{\n']
        offset=0
        for field,ty,*count in fields:
            n=count[0] if count else 1; width=SIZES[ty]
            def read(at):return f'{ty}::from_le_bytes(bytes[{at}..{at+width}].try_into().ok()?)'
            value='['+','.join(read(offset+i*width) for i in range(n))+']' if count else read(offset)
            shared.append(f'{field}: {value},\n'); offset+=n*width
        shared += ['}) }\n',f'pub fn encode(&self)->[u8;{size}] {{ let mut bytes=[0;{size}];\n'];offset=0
        for field,ty,*count in fields:
            for i in range(count[0] if count else 1):
                width=SIZES[ty];v=f'self.{field}'+(f'[{i}]' if count else '')
                shared.append(f'bytes[{offset}..{offset+width}].copy_from_slice(&{v}.to_le_bytes());\n');offset+=width
        shared += ['bytes } }\n']
    shared += ['pub const INPUT_SECTION_COUNT: usize = INPUT_SECTIONS.len();\n',f'pub const OPTIONAL_NONE: i32 = {data["optional_none"]};\n']
    raw=[banner,'// Private imports. Public methods validate every slice before crossing this boundary.\n']
    dev=[banner,'use super::{invoke,State};\nuse incant_wasm_runtime::Call;\nuse wasmtime::{Caller,Linker,Result};\npub fn install(linker: &mut Linker<State>)->Result<()> {\n']
    dispatch=[banner,'use crate::Call;\npub(crate) fn decode(op:u32, args:[i32;4])->Option<Call> {Some(match op {\n']
    c=[f'/* Generated by tools/generate_wasm_sdk.py; registry SHA256 {digest}. */\n']
    for f in funcs:
        alias=f['namespace']+'_'+f['name']; params=', '.join(n+': '+t for n,t in f['params']); ret=' -> '+f['result'] if f['result'] else ''
        raw += [f'#[cfg(target_arch="wasm32")] #[link(wasm_import_module="{f["namespace"]}")] unsafe extern "C" {{ #[link_name="{f["name"]}"] pub fn {alias}({params}){ret}; }}\n',f'#[cfg(not(target_arch="wasm32"))] pub unsafe fn {alias}({params}){ret} {{ '+''.join(f'let _={n};' for n,_ in f['params'])+'panic!("module imports require wasm32") }\n']
        invoke=f'invoke(c, epoch, {f["call"]})'+('' if f['result'] else '.map(|_| ())')
        dev.append(f'linker.func_wrap("{f["namespace"]}","{f["name"]}",|c: Caller<\'_,State>, {params}| {invoke})?;\n')
        lets=''.join(f'let {n}=args[{i}];' for i,(n,_) in enumerate(f['params'][1:]))
        dispatch.append(f'{f["opcode"]} => {{ {lets} {f["call"]} }},\n')
        struct='w2c_'+f['namespace'].replace('_','__'); host='h' if f['namespace']=='incant_v1' else '&h->core'
        args=[n for n,_ in f['params'][1:]];arguments=','.join(args+['0']*(4-len(args)))
        cparams=', '.join(('uint64_t' if t=='i64' else 'uint32_t')+' '+n for n,t in f['params'])
        c.append(f'{"uint32_t" if f["result"] else "void"} {struct}_{f["name"]}(struct {struct}* h, {cparams}) {{ '+('return ' if f['result'] else '')+f'invoke({host},{f["opcode"]},epoch,{arguments}); }}\n')
    dev.append('Ok(()) }\n');dispatch.append('_=>return None,}) }\n')
    tags=[banner,'use incant_input::{KeyCode,MouseButton,GamepadButton};\n']
    for name,source,func in [('Key','KeyCode','key'),('MouseButton','MouseButton','mouse'),('GamepadButton','GamepadButton','button')]:
        tags += [f'pub(super) fn {func}(value:{source})->u8 {{ match value {{'+''.join(f'{source}::{n}=>incant_wasm_abi::{name}::{n} as u8,' for n,_ in data['enums'][name])+'} }\n']
    tags.append('pub(super) const GAMEPAD_BUTTONS: [GamepadButton;17] = ['+','.join('GamepadButton::'+n for n,_ in data['enums']['GamepadButton'])+'];\n')
    namespaces={'w2c_'+n.replace('_','__'):field for n,field in data['namespaces'].items()}
    header='/* Generated namespace contexts; see native-v1.json. */\n'
    for namespace,field in namespaces.items():
        header+=f'struct {namespace} {{ '+('incant_import callback; void* context; wasm_rt_memory_t* memory;' if field=='imports' else 'struct w2c_incant__v1 core;')+' };\n'
    python=f'# Generated by tools/generate_wasm_sdk.py; registry SHA256 {digest}.\nABI_VERSION = {data["abi_version"]}\nNAMESPACES = {namespaces!r}\n'
    return {'tools/wasm_abi.py':python,'crates/incant_wasm_runtime/c/generated.h':header,'crates/incant_wasm_abi/src/lib.rs':''.join(shared),'sdk/rust/src/raw.rs':''.join(raw),'crates/incant_wasm_dev/src/generated.rs':''.join(dev),'crates/incant_wasm_runtime/src/generated.rs':''.join(dispatch),'crates/incant_wasm_runtime/src/input_tags.rs':''.join(tags),'crates/incant_wasm_runtime/c/generated.inc':''.join(c)}


def outputs():
    data=REGISTRY.read_bytes(); result=generate(json.loads(data),hashlib.sha256(data).hexdigest())
    formatter = shutil.which('rustfmt') or subprocess.check_output(['rustup','which','--toolchain','1.99.0','rustfmt'],text=True).strip()
    for path,value in result.items():
        if path.endswith('.rs'):
            result[path]=subprocess.run([formatter,'--edition','2024'],input=value,text=True,capture_output=True,check=True).stdout
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,data in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=data:raise SystemExit(f'generated ABI differs: {name}')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data)

if __name__=='__main__':main()
