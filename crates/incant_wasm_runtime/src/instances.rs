//! Trusted cold catalog and incarnation-bound membership; no authoring on ticks.
use crate::BoundaryError as Error;
use incant_runtime::{EntityIdentity, NativeWorld, StableId};
use incant_types::{CoroutineValue, properties::PropertyBudget};
use incant_wasm_abi::{self as abi, instances::Snapshot};
use sha2::{Digest, Sha256};
use std::{collections::BTreeMap, sync::Arc};

// Shared typed/TS limits and the no_std wire decoder must never drift.
const _: () = {
    assert!(incant_types::properties::MAX_INSTANCES == abi::INSTANCE_MAX_ROWS);
    assert!(incant_types::properties::MAX_PROP_NODES == abi::INSTANCE_MAX_PROP_NODES);
    assert!(incant_types::properties::MAX_PROP_BYTES == abi::INSTANCE_MAX_PROP_BYTES);
    assert!(incant_types::properties::MAX_PROP_DEPTH == abi::INSTANCE_MAX_PROP_DEPTH);
};
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Catalog {
    scene: [u8; 32],
    rows: Vec<(StableId, Box<[u8]>)>,
    digest: [u8; 32],
}
impl Catalog {
    /// Input is already typed cold data. Validate again at this public boundary.
    pub fn new(
        scene: [u8; 32],
        rows: BTreeMap<StableId, BTreeMap<String, CoroutineValue>>,
    ) -> Result<Self, Error> {
        if rows.len() > abi::INSTANCE_MAX_ROWS {
            return Err(Error::Limit("Wasm instances"));
        }
        let mut budget = PropertyBudget::default();
        let mut encoded = Vec::with_capacity(rows.len());
        for (id, props) in rows {
            let mut bytes = Vec::new();
            budget
                .object(&props, 0, &mut |value| bytes.extend_from_slice(value))
                .map_err(|_| Error::Abi("Wasm initial properties"))?;
            encoded.push((id, bytes.into_boxed_slice()));
        }
        let mut frame = Vec::new();
        encode(&mut frame, encoded.iter().map(|(id, p)| (*id, p.as_ref())))?;
        Snapshot::parse(&frame).map_err(|_| Error::Abi("Wasm instance encoding"))?;
        let mut hash = Sha256::new();
        hash.update(b"Incant Wasm initial instances v1\0");
        hash.update(scene);
        hash.update(frame);
        Ok(Self {
            scene,
            rows: encoded,
            digest: hash.finalize().into(),
        })
    }
    pub fn digest(&self) -> [u8; 32] {
        self.digest
    }
    pub fn is_empty(&self) -> bool {
        self.rows.is_empty()
    }
    pub fn scene(&self) -> [u8; 32] {
        self.scene
    }
    pub fn validate_world(&self, world: &NativeWorld) -> Result<(), Error> {
        if world.source_scene_fingerprint() != self.scene {
            return Err(Error::Abi("Wasm instance scene pairing"));
        }
        Ok(())
    }
    pub fn validate_initial(&self, world: &NativeWorld) -> Result<(), Error> {
        self.validate_world(world)?;
        if world.tick() != 0
            || self
                .rows
                .iter()
                .any(|(id, _)| world.entity_identity(*id).is_none())
        {
            return Err(Error::Abi("Wasm initial owners"));
        }
        Ok(())
    }
    /// Constant data generated by the trusted cold cook, never a runtime path.
    pub fn from_frame(scene: [u8; 32], bytes: &[u8]) -> Result<Self, Error> {
        let frame = Snapshot::parse(bytes).map_err(|_| Error::Abi("Wasm instance frame"))?;
        let mut rows = Vec::with_capacity(frame.len());
        let mut tail = &bytes[abi::instances::HEADER..];
        for _ in 0..frame.len() {
            let id = StableId(tail[..16].try_into().unwrap());
            let n = u32::from_le_bytes(tail[16..20].try_into().unwrap()) as usize;
            rows.push((id, tail[24..24 + n].into()));
            tail = &tail[24 + n..];
        }
        let mut hash = Sha256::new();
        hash.update(b"Incant Wasm initial instances v1\0");
        hash.update(scene);
        hash.update(bytes);
        Ok(Self {
            scene,
            rows,
            digest: hash.finalize().into(),
        })
    }
    pub fn frame(&self) -> Vec<u8> {
        let mut bytes = Vec::new();
        encode(
            &mut bytes,
            self.rows.iter().map(|(id, p)| (*id, p.as_ref())),
        )
        .expect("validated catalog");
        bytes
    }
}
fn encode<'a>(
    out: &mut Vec<u8>,
    rows: impl Iterator<Item = (StableId, &'a [u8])>,
) -> Result<(), Error> {
    out.clear();
    out.extend_from_slice(abi::INSTANCE_MAGIC);
    out.extend(1u32.to_le_bytes());
    out.extend([0; 12]);
    let mut n = 0u32;
    for (id, props) in rows {
        if out.len() + 24 + props.len() > abi::INSTANCE_MAX_BYTES {
            return Err(Error::Limit("Wasm instance frame"));
        }
        out.extend(id.0);
        out.extend((props.len() as u32).to_le_bytes());
        out.extend([0; 4]);
        out.extend(props);
        n += 1;
    }
    out[12..16].copy_from_slice(&n.to_le_bytes());
    let len = (out.len() - 24) as u32;
    out[16..20].copy_from_slice(&len.to_le_bytes());
    Ok(())
}
#[derive(Default)]
pub(crate) struct State {
    catalog: Option<Arc<Catalog>>,
    active: BTreeMap<StableId, EntityIdentity>,
    bound: bool,
    frame: Vec<u8>,
}
impl State {
    pub fn configured(catalog: Arc<Catalog>) -> Self {
        Self {
            catalog: Some(catalog),
            ..Self::default()
        }
    }
    pub fn catalog(&self) -> Option<Arc<Catalog>> {
        self.catalog.clone()
    }
    pub fn same_catalog(&self, other: &Self) -> bool {
        self.catalog == other.catalog
    }
    pub fn bind_initial(&mut self, world: &NativeWorld) -> Result<(), Error> {
        if self.bound {
            return Err(Error::Abi("instance owners already bound"));
        }
        if let Some(c) = &self.catalog {
            c.validate_world(world)?;
            if world.tick() != 0 {
                return Err(Error::Abi("Wasm instances require fresh startup"));
            }
            self.active = c
                .rows
                .iter()
                .map(|(id, _)| {
                    world
                        .entity_identity(*id)
                        .map(|identity| (*id, identity))
                        .ok_or(Error::Abi("Wasm instance owner absent"))
                })
                .collect::<Result<_, _>>()?;
        }
        self.bound = true;
        Ok(())
    }
    pub fn begin(&mut self, world: &NativeWorld) -> Result<(), Error> {
        if self.catalog.is_some() && !self.bound {
            return Err(Error::Abi("Wasm instance catalog unbound"));
        }
        self.prune(world);
        let active = &self.active;
        let rows = self
            .catalog
            .as_ref()
            .into_iter()
            .flat_map(|c| c.rows.iter())
            .filter(|(id, _)| active.contains_key(id))
            .map(|(id, p)| (*id, p.as_ref()));
        encode(&mut self.frame, rows)
    }
    pub fn prune(&mut self, world: &NativeWorld) {
        self.active
            .retain(|id, identity| world.matches_entity_identity(*id, *identity));
    }
    pub fn frame(&self) -> &[u8] {
        &self.frame
    }
    pub fn checkpoint(&self, world: &NativeWorld) -> Option<Vec<u8>> {
        self.catalog.as_ref().map(|c| {
            let ids: Vec<_> = self
                .active
                .iter()
                .filter(|(id, identity)| world.matches_entity_identity(**id, **identity))
                .map(|(id, _)| id.0)
                .collect();
            let mut out = c.digest.to_vec();
            out.extend((ids.len() as u32).to_le_bytes());
            for id in ids {
                out.extend(id);
            }
            out
        })
    }
    pub fn restored(&self, bytes: Option<&[u8]>, world: &NativeWorld) -> Result<Self, Error> {
        let Some(c) = &self.catalog else {
            if bytes.is_some() {
                return Err(Error::Abi("unexpected instance catalog"));
            }
            return Ok(Self::default());
        };
        c.validate_world(world)?;
        let (digest, ids) =
            abi::instances::checkpoint(bytes.ok_or(Error::Abi("missing instance membership"))?)
                .map_err(|_| Error::Abi("instance membership framing"))?;
        if digest != c.digest {
            return Err(Error::Abi("instance catalog mismatch"));
        }
        let mut active = BTreeMap::new();
        for raw in ids {
            let id = StableId(raw);
            if c.rows.binary_search_by_key(&id, |r| r.0).is_err() {
                return Err(Error::Abi("unknown instance owner"));
            }
            active.insert(
                id,
                world
                    .entity_identity(id)
                    .ok_or(Error::Abi("restored instance owner absent"))?,
            );
        }
        Ok(Self {
            catalog: Some(c.clone()),
            active,
            bound: true,
            frame: Vec::new(),
        })
    }
}
