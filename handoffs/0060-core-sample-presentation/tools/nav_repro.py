#!/usr/bin/env python3
"""nav_repro.py OUT.rs [x y z x y z ...]: emit a self-contained Rust example that bakes the
Core Sample navmesh from samples/core/art/level.py colliders with the engine's own
navigation_geometry + NavigationMesh::rebuild, then runs find_path for each start/end
pair (snap 2, max_visited 2048, as gameplay.ts does) and prints the exact Result.
Run through nav_repro.sh; development reproduction only.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'samples/core'))
from art import ids, level  # noqa: E402


def f(v):
    return repr(float(v))


def part(p):
    s = p['shape']
    if s['type'] == 'box':
        shape = 'PrimitiveColliderShape::Box { half_extents: [%s] }' % ', '.join(map(f, s['half_extents']))
    elif s['type'] == 'sphere':
        shape = 'PrimitiveColliderShape::Sphere { radius: %s }' % f(s['radius'])
    else:
        shape = 'PrimitiveColliderShape::Capsule { half_height: %s, radius: %s }' % (f(s['half_height']), f(s['radius']))
    return ('ColliderPart { id: "%s".into(), translation: [%s], rotation: [%s], shape: %s }'
            % (p['id'], ', '.join(map(f, p['translation'])), ', '.join(map(f, p['rotation'])), shape))


def sweep_points(step=1.25):
    """Capsule-centre probe points over the floor, both ramps and the upper mesa."""
    pts = []
    x = level.PLAY_X[0] + 0.6
    while x < level.PLAY_X[1] - 0.6:
        z = level.PLAY_Z[0] + 0.6
        while z < level.PLAY_Z[1] - 0.6:
            upper = z < level.NORTH_PLATEAU['z'][1] or (level.EAST_SHELF['x'][0] <= x and z < level.EAST_SHELF['z'][1])
            pts.append((x, (level.UPPER_Y if upper else level.FLOOR_Y) + level.CENTRE, z))
            z += step
        x += step
    for ramp in level.RAMPS.values():
        for k in range(12):
            t = (k + 0.5) / 12
            z = ramp['z_low'] + (ramp['z_high'] - ramp['z_low']) * t
            for x in (ramp['x'][0] + 0.5, sum(ramp['x']) / 2, ramp['x'][1] - 0.5):
                pts.append((x, level.ramp_height(ramp, z) + level.CENTRE, z))
    return pts


def main():
    out = Path(sys.argv[1])
    if len(sys.argv) > 2 and sys.argv[2] == '--sweep':
        pts = sweep_points()
        pairs = []
        for i, a in enumerate(pts):
            for j in range(0, len(pts), 7):
                b = pts[(j + i * 13) % len(pts)]
                pairs.append((a, b))
    else:
        values = [float(v) for v in sys.argv[2:]]
        pairs = [(values[i:i + 3], values[i + 3:i + 6]) for i in range(0, len(values), 6)]
    colliders = level.colliders()
    keys = {'ground': ids.entity(6), 'walls': ids.entity(7), 'rocks': ids.entity(8)}
    sources = []
    for name, parts in colliders.items():
        sources.append('    sources.insert("%s:collider".to_string(), navigation_geometry(&ColliderShape::Compound { parts: vec![\n        %s,\n    ] }).unwrap());'
                       % (keys[name], ',\n        '.join(part(p) for p in parts)))
    s = level.navigation_settings()
    settings = ('NavigationSettings { min: [%s], max: [%s], cell_size: %s, cell_height: %s, tile_cells: %d, '
                'agent_radius: %s, agent_height: %s, max_climb: %s, max_slope_degrees: %s }'
                % (', '.join(map(f, s['min'])), ', '.join(map(f, s['max'])), f(s['cell_size']), f(s['cell_height']),
                   s['tile_cells'], f(s['agent_radius']), f(s['agent_height']), f(s['max_climb']),
                   f(s['max_slope_degrees'])))
    pair_rows = ',\n    '.join('([%s], [%s])' % (', '.join(map(f, a)), ', '.join(map(f, b))) for a, b in pairs)
    out.write_text('''//! Generated by handoffs/0060-core-sample-presentation/tools/nav_repro.py (development only).
use incant_nav::{NavigationMesh, NavigationSettings, PathRequest};
use incant_physics_runtime::navigation_geometry;
use incant_types::{ColliderPart, ColliderShape, PrimitiveColliderShape};
use std::collections::BTreeMap;

const PAIRS: &[([f32; 3], [f32; 3])] = &[
    %s
];

fn main() {
    // Optional overrides: quiet cell_size cell_height tile_cells max_climb
    let args: Vec<String> = std::env::args().skip(1).collect();
    let verbose = args.is_empty();
    let pick = |i: usize| args.get(i).and_then(|v| v.parse::<f32>().ok());
    let mut sources = BTreeMap::new();
%s
    let mut settings = %s;
    if let Some(v) = pick(1) { settings.cell_size = v; }
    if let Some(v) = pick(2) { settings.cell_height = v; }
    if let Some(v) = pick(3) { settings.tile_cells = v as u16; }
    if let Some(v) = pick(4) { settings.max_climb = v; }
    println!("settings cell_size={} cell_height={} tile_cells={} max_climb={}", settings.cell_size,
             settings.cell_height, settings.tile_cells, settings.max_climb);
    let mut mesh = NavigationMesh::default();
    let report = mesh.rebuild(&settings, &sources).unwrap();
    println!("polygons={} tiles={}", report.polygons, report.rebuilt.len());
    let (mut ok, mut none, mut errors, mut max_visited, mut max_points) = (0u32, 0u32, 0u32, 0u32, 0usize);
    let mut heavy: Vec<(u32, [f32; 3], [f32; 3])> = Vec::new();
    let mut unroutable: BTreeMap<String, u32> = BTreeMap::new();
    for &(start, end) in PAIRS {
        let request = PathRequest { start, end, snap_distance: 2.0, max_visited: 2048 };
        match mesh.find_path(&request) {
            Ok(Some(path)) => {
                ok += 1;
                max_visited = max_visited.max(path.visited);
                heavy.push((path.visited, start, end));
                max_points = max_points.max(path.points.len());
                if verbose {
                    println!("{start:?} -> {end:?}: ok points={} visited={}", path.points.len(), path.visited);
                }
            }
            Ok(None) => {
                none += 1;
                for p in [start, end] {
                    *unroutable.entry(format!("{:.1},{:.1}", p[0], p[2])).or_default() += 1;
                }
                if verbose {
                    println!("{start:?} -> {end:?}: no route");
                }
            }
            Err(error) => {
                errors += 1;
                println!("{start:?} -> {end:?}: ERROR {error}");
            }
        }
    }
    heavy.sort_by(|a, b| b.0.cmp(&a.0));
    for (v, a, b) in heavy.iter().take(4) {
        println!("heavy {v}: {a:?} -> {b:?}");
    }
    let mut worst: Vec<_> = unroutable.into_iter().collect();
    worst.sort_by(|a, b| b.1.cmp(&a.1));
    println!("most unroutable points: {:?}", &worst[..worst.len().min(12)]);
    println!("queries ok={ok} none={none} error={errors} max_visited={max_visited} max_points={max_points}");
}
''' % (pair_rows, '\n'.join(sources), settings), encoding='utf-8')


if __name__ == '__main__':
    main()
